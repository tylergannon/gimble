<h1 data-testid="title">About</h1>
<p>
	Gimble is a Go library and runtime for writing agent workflows as ordinary
	Go. It is not tied to Codex, Claude Code, or any other host. Those are
	harnesses Gimble can drive; you can also provide an adapter for a different
	harness or run a workflow without the web UI.
</p>
<p>
	This page is plain SvelteKit. It calls nothing, and Go serves it out of the
	binary like every other route.
</p>
